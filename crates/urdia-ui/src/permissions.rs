    #[tokio::test]
    async fn trusted_session_requires_prepare_and_confirm_then_revalidates() {
        let broker = InteractivePermissionBroker::with_trusted_session("Public provider");
        let session_id = SessionId::new();
        let task = tokio::spawn({
            let broker = broker.clone();
            let session_id = session_id.clone();
            async move { broker.authorize(trusted_request(session_id, 4)).await }
        });
        let pending = wait_for_pending(&broker).await;
        let before = broker.trusted_state().expect("trusted state should exist");
        assert_eq!(before.status, TrustedSessionStatus::AwaitingRequest);
        let challenge = broker
            .prepare_trusted_session(pending.id, pending.revision)
            .expect("real pending request should prepare a challenge");
        assert_eq!(challenge.provider_label, "Public provider");
        assert_eq!(
            challenge.capabilities,
            TRUSTED_SESSION_CAPABILITIES.to_vec()
        );
        assert!(challenge.workspace.starts_with('/'));
        let prepared = broker.trusted_state().expect("trusted state should exist");
        assert_eq!(prepared.status, TrustedSessionStatus::AwaitingConfirmation);
        assert_eq!(prepared.challenge, Some(challenge.clone()));

        let active = broker
            .confirm_trusted_session(challenge.id, challenge.revision)
            .expect("challenge should activate a policy");
        assert_eq!(active.status, TrustedSessionStatus::Active);
        assert_eq!(active.ttl_seconds, TRUSTED_SESSION_TTL_SECONDS);
        assert!(active.expires_at.is_some());
        let decision = task
            .await
            .expect("authorization task should join")
            .expect("trusted decision should arrive");
        let grant = decision
            .trusted_grant()
            .expect("activation should resolve the triggering request as trusted");
        let follow_up = trusted_request(session_id, 5);
        assert_eq!(
            broker
                .authorize(follow_up.clone())
                .await
                .unwrap()
                .trusted_grant(),
            Some(grant.clone())
        );
        broker
            .revalidate_trusted(&follow_up, &grant)
            .await
            .expect("active policy should revalidate");

        let revoked = broker
            .revoke_trusted_session()
            .expect("revocation should succeed");
        assert_eq!(revoked.status, TrustedSessionStatus::Revoked);
        assert!(broker.revalidate_trusted(&follow_up, &grant).await.is_err());
        let pending_again = tokio::spawn({
            let broker = broker.clone();
            async move { broker.authorize(follow_up).await }
        });
        let pending_again_view = wait_for_pending(&broker).await;
        assert_eq!(
            broker.trusted_state().expect("trusted state").status,
            TrustedSessionStatus::AwaitingRequest
        );
        let replacement = broker
            .prepare_trusted_session(pending_again_view.id, pending_again_view.revision)
            .expect("a new request should permit reactivation after revocation");
        broker
            .confirm_trusted_session(replacement.id, replacement.revision)
            .expect("replacement policy should activate");
        assert!(
            pending_again
                .await
                .expect("authorization task should join")
                .expect("trusted decision should arrive")
                .trusted_grant()
                .is_some()
        );
    }

